#!/usr/bin/env python3
"""Generate the fully expanded SECDED (Hsiao) ECC codecs for VCACHE-3D.

Every codec is emitted as flat, explicitly unrolled XOR trees so that
synthesis, formal equivalence, and physical-design timing analysis all see
exactly the netlist that is reviewed in-tree (the same convention already used
by tools/generate_chi_ultra_telemetry.py).

Codes
-----
Hsiao odd-weight-column SECDED:
  * every column of H has odd weight  ->  a single-bit error always produces an
    odd-parity syndrome, a double-bit error always produces an even, non-zero
    syndrome, so SEC and DED are distinguished without a separate overall
    parity bit;
  * check-bit columns are the unit vectors, so the encoder is a pure XOR of
    data bits (no back substitution);
  * data columns are chosen weight-3 first, then weight-5, ..., greedily
    load-balancing the rows of H.  Balanced rows == balanced XOR-tree depth ==
    the best achievable ECC critical path, which matters because this codec
    sits in the L3 hit path.

Widths generated: 32, 64, 128, 256, 512 data bits.
The 128-bit codec is the workhorse: a 64 B cache line is protected as four
independent 128+9 sublines, which lets the design tolerate one hard failure per
subline (i.e. one failing bond lane per 128-bit slice) and still return data.
"""
from itertools import combinations
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTDIR = ROOT / "rtl" / "ecc"

WIDTHS = [32, 64, 128, 256, 512]


def odd_weight_column_count(r: int) -> int:
    """Number of distinct odd-weight (>=3) column vectors available with r rows."""
    from math import comb
    return sum(comb(r, w) for w in range(3, r + 1, 2))


def check_bits(data_bits: int) -> int:
    """Smallest r that satisfies both the Hamming bound and the Hsiao
    odd-weight-column budget (the latter binds for small widths: SECDED(32)
    needs 7 check bits as an Hsiao code even though the Hamming bound allows
    6, because only 26 odd-weight columns exist with r = 6)."""
    r = 1
    while (1 << r) < data_bits + r + 1:
        r += 1
    while odd_weight_column_count(r) < data_bits:
        r += 1
    return r


def hsiao_columns(data_bits: int, r: int):
    """Return `data_bits` distinct odd-weight (>=3) column vectors of length r,
    greedily balancing the per-row load."""
    pool = []
    for w in range(3, r + 1, 2):
        pool.extend(combinations(range(r), w))
    if len(pool) < data_bits:
        raise ValueError("not enough odd-weight columns")
    row_load = [0] * r
    chosen = []
    # Group by weight so that low-weight (cheap) columns are consumed first.
    by_weight = {}
    for c in pool:
        by_weight.setdefault(len(c), []).append(c)
    for w in sorted(by_weight):
        cands = by_weight[w]
        while cands and len(chosen) < data_bits:
            # pick the candidate whose rows are currently least loaded
            best = min(cands, key=lambda c: (max(row_load[i] for i in c),
                                             sum(row_load[i] for i in c), c))
            cands.remove(best)
            chosen.append(best)
            for i in best:
                row_load[i] += 1
        if len(chosen) == data_bits:
            break
    return chosen, row_load


def emit_codec(width: int):
    r = check_bits(width)
    cols, row_load = hsiao_columns(width, r)
    rows = [[d for d in range(width) if i in cols[d]] for i in range(r)]

    L = []
    def p(s=""):
        L.append(s)

    p("// ---------------------------------------------------------------------------")
    p(f"// AUTO-GENERATED by gen/vc3d_gen_ecc.py -- DO NOT HAND EDIT.")
    p(f"// SECDED (Hsiao) codec for {width} data bits + {r} check bits.")
    p(f"// Code distance 4: corrects 1 bit, detects 2 bits, detects all odd-weight")
    p(f"// error patterns.  Row loads (XOR-tree fan-in per check bit): {row_load}")
    p(f"// Max fan-in {max(row_load)}  ->  balanced XOR depth ceil(log2(max)) = "
      f"{max(row_load).bit_length()}.")
    p("// ---------------------------------------------------------------------------")
    p("`timescale 1ns/1ps")
    p("")
    # ------------------------------------------------------------------ encoder
    p(f"module vc3d_secded_enc_{width} (")
    p(f"    input  wire [{width-1}:0] data_i,")
    p(f"    output wire [{r-1}:0] check_o")
    p(");")
    p("")
    for i in range(r):
        terms = rows[i]
        p(f"    // check bit {i}: {len(terms)} taps")
        p(f"    assign check_o[{i}] =")
        for k, d in enumerate(terms):
            sep = ";" if k == len(terms) - 1 else " ^"
            lead = "        " if k else "          "
            p(f"{lead}data_i[{d}]{sep}")
        p("")
    p("endmodule")
    p("")
    # ------------------------------------------------------------------ decoder
    p(f"module vc3d_secded_dec_{width} (")
    p(f"    input  wire [{width-1}:0] data_i,")
    p(f"    input  wire [{r-1}:0] check_i,")
    p(f"    input  wire poison_i,")
    p(f"    output wire [{width-1}:0] data_o,")
    p(f"    output wire [{r-1}:0] syndrome_o,")
    p("    output wire ce_o,           // corrected single-bit error")
    p("    output wire ue_o,           // uncorrectable (double bit) error")
    p("    output wire ce_in_check_o,  // the corrected bit was a check bit")
    p("    output wire poison_o")
    p(");")
    p("")
    p(f"    wire [{r-1}:0] syndrome;")
    for i in range(r):
        terms = rows[i]
        p(f"    assign syndrome[{i}] = check_i[{i}]")
        for d in terms:
            p(f"        ^ data_i[{d}]")
        p("        ;")
    p("")
    p("    assign syndrome_o = syndrome;")
    p("")
    p("    wire syndrome_nz  = |syndrome;")
    p("    wire syndrome_odd = ^syndrome;")
    p("    // Hsiao: odd syndrome parity == single-bit (correctable) error.")
    p("    assign ce_o = syndrome_nz &  syndrome_odd & ~poison_i;")
    p("    assign ue_o = (syndrome_nz & ~syndrome_odd) | poison_i;")
    p("    assign poison_o = poison_i | (syndrome_nz & ~syndrome_odd);")
    p("")
    p(f"    wire [{width-1}:0] correct;")
    for d in range(width):
        val = 0
        for i in cols[d]:
            val |= (1 << i)
        p(f"    assign correct[{d}] = (syndrome == {r}'d{val});")
    p("")
    p("    // A syndrome equal to a unit vector points at a check bit, not data.")
    chk_terms = " | ".join(f"(syndrome == {r}'d{1 << i})" for i in range(r))
    p(f"    assign ce_in_check_o = ce_o & ({chk_terms});")
    p("")
    p("    assign data_o = data_i ^ (correct & {%d{ce_o}});" % width)
    p("")
    p("endmodule")
    p("")

    # ------------------------------------------------- split (pipelined) pair
    p("// ---------------------------------------------------------------------------")
    p(f"// Pipelined split of the same code: vc3d_secded_syn_{width} computes the")
    p("// syndrome (stage 1) and vc3d_secded_cor_{} applies the correction".format(width))
    p("// (stage 2) from a REGISTERED syndrome.  Splitting the decoder is what lets")
    p("// the ECC sit in a 3 GHz pipeline: the XOR tree and the 1-of-N correction")
    p("// compare are each about half of the combinational decoder.")
    p("// ---------------------------------------------------------------------------")
    p(f"module vc3d_secded_syn_{width} (")
    p(f"    input  wire [{width-1}:0] data_i,")
    p(f"    input  wire [{r-1}:0] check_i,")
    p(f"    output wire [{r-1}:0] syndrome_o")
    p(");")
    p("")
    for i in range(r):
        terms = rows[i]
        p(f"    assign syndrome_o[{i}] = check_i[{i}]")
        for d in terms:
            p(f"        ^ data_i[{d}]")
        p("        ;")
    p("")
    p("endmodule")
    p("")
    p(f"module vc3d_secded_cor_{width} (")
    p(f"    input  wire [{width-1}:0] data_i,      // registered, same beat as syndrome")
    p(f"    input  wire [{r-1}:0] syndrome_i,")
    p("    input  wire poison_i,")
    p(f"    output wire [{width-1}:0] data_o,")
    p("    output wire ce_o,")
    p("    output wire ue_o,")
    p("    output wire poison_o")
    p(");")
    p("")
    p("    wire syndrome_nz  = |syndrome_i;")
    p("    wire syndrome_odd = ^syndrome_i;")
    p("    assign ce_o     = syndrome_nz &  syndrome_odd & ~poison_i;")
    p("    assign ue_o     = (syndrome_nz & ~syndrome_odd) | poison_i;")
    p("    assign poison_o = poison_i | (syndrome_nz & ~syndrome_odd);")
    p("")
    p(f"    wire [{width-1}:0] correct;")
    for d in range(width):
        val = 0
        for i in cols[d]:
            val |= (1 << i)
        p(f"    assign correct[{d}] = (syndrome_i == {r}'d{val});")
    p("")
    p("    assign data_o = data_i ^ (correct & {%d{ce_o}});" % width)
    p("")
    p("endmodule")
    p("")
    return "\n".join(L) + "\n", cols, r


def main():
    OUTDIR.mkdir(parents=True, exist_ok=True)
    manifest = []
    for w in WIDTHS:
        text, cols, r = emit_codec(w)
        path = OUTDIR / f"vc3d_secded_{w}.v"
        path.write_text(text)
        manifest.append((w, r, len(text.splitlines()), path.name))
        # ---- golden self-check of the generated code -------------------------
        selftest(w, r, cols)
    print("width  check  lines  file")
    for w, r, n, f in manifest:
        print(f"{w:5d}  {r:5d}  {n:5d}  {f}")


def selftest(width, r, cols):
    """Exhaustively verify SEC and DED behaviour of the generated H matrix."""
    def syn_of_bit(d):
        s = 0
        for i in cols[d]:
            s |= 1 << i
        return s

    seen = {}
    for d in range(width):
        s = syn_of_bit(d)
        assert s != 0, "zero column"
        assert bin(s).count("1") % 2 == 1, "even weight column"
        assert s not in seen, f"duplicate column {d} vs {seen[s]}"
        seen[s] = d
    for i in range(r):
        s = 1 << i
        assert s not in seen, "check column collides with data column"
        seen[s] = ("chk", i)
    # any double error must produce an even, non-zero syndrome
    allcols = [syn_of_bit(d) for d in range(width)] + [1 << i for i in range(r)]
    n = len(allcols)
    for a in range(0, n, max(1, n // 64)):
        for b in range(a + 1, n, max(1, n // 64)):
            s = allcols[a] ^ allcols[b]
            assert s != 0 and bin(s).count("1") % 2 == 0, "DED violation"
    print(f"[selftest] SECDED({width},{r}) SEC/DED properties verified")


if __name__ == "__main__":
    main()
