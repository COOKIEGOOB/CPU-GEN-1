#!/usr/bin/env python3
"""Regenerate filelist_base.f / filelist_cache.f / filelist_tb.f.

Kept generated rather than hand-maintained so that a new RTL file cannot be
silently left out of synthesis (the classic 'it simulated but did not build'
failure).  `make check-vcache3d-generated` fails if these are stale.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

BASE_DIRS  = ["rtl/ecc", "rtl/repair", "rtl/power", "rtl/perf", "rtl/csr",
              "rtl/slice", "rtl/stack", "rtl/top"]
CACHE_DIRS = ["rtl/stack", "rtl/power"]

# the cache dielet carries only the stacked array, its bond endpoint and the
# repair register fabric -- no cache control logic at all
CACHE_ONLY = {
    "rtl/stack/vc3d_stack_subarray.v",
    "rtl/stack/vc3d_stack_bank_array.v",
    "rtl/stack/vc3d_stack_die_top.v",
    "rtl/stack/vc3d_bond_lane.v",
    "rtl/stack/vc3d_bond_crc16.v",
    "rtl/stack/vc3d_bond_channel.v",
    "rtl/stack/vc3d_bond_link.v",
    "rtl/power/vc3d_thermal_sensor.v",
}


def collect(dirs):
    out = []
    for d in dirs:
        p = os.path.join(ROOT, d)
        if not os.path.isdir(p):
            continue
        for f in sorted(os.listdir(p)):
            if f.endswith(".v"):
                out.append(os.path.join(d, f))
    return out


def write(path, header, incdirs, files):
    with open(os.path.join(ROOT, path), "w") as fh:
        fh.write(f"// {header}\n")
        fh.write("// GENERATED by gen/vc3d_gen_filelists.py -- do not edit.\n")
        for i in incdirs:
            fh.write(f"+incdir+{i}\n")
        for f in files:
            fh.write(f + "\n")
    return len(files)


def main():
    base = [f for f in collect(BASE_DIRS)]
    cache = [f for f in collect(CACHE_DIRS) if f in CACHE_ONLY]
    tb = sorted("tb/" + f for f in os.listdir(os.path.join(ROOT, "tb"))
                if f.endswith(".sv"))

    n1 = write("filelist_base.f",  "VCACHE-3D base die (logic tier)",
               ["include"], base)
    n2 = write("filelist_cache.f", "VCACHE-3D cache dielet (stacked SRAM tier)",
               ["include"], cache)
    n3 = write("filelist_tb.f",    "VCACHE-3D testbenches (needs filelist_base.f too)",
               ["include", "tb"], tb)

    print(f"filelist_base.f  : {n1} files")
    print(f"filelist_cache.f : {n2} files")
    print(f"filelist_tb.f    : {n3} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
