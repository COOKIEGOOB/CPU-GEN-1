#!/usr/bin/env python3
"""Generate the fully expanded macro-sliced stacked-die SRAM array.

The dielet Frequency Upgrade splits every legacy 1024 x 148 subarray macro
into VC3D_STACK_MACRO_SLICES (default 4) direct SRAM macro slices of
256 x 148 with divided local bitlines.  Each slice is an independent
vc3d_stack_macro_cell, and each bank is expanded explicitly (rather than a
generate loop) because physical design places and power-gates every local
bitline independently and the floorplan scripts in pd/openroad key off the
instance names produced here.

The generated module vc3d_stack_macro_die_array has the same port list as the
legacy generated vc3d_stack_die_array, so it is a drop-in replacement in
rtl/stack/vc3d_stack_die_top.v.

Run `make -C _noc/vcache3d gen` to regenerate.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "rtl" / "stack" / "vc3d_stack_macro_slice_array.v"

BANKS = 32
SUBARRAYS = 16
ROWS = 1024
AW = 10
DW = 144
SPARE_ROWS = 4
SPARE_COLS = 4
COL_ID_W = 6
SLICES = 4
SLICE_DEPTH = 256
SLICE_AW = 8
SLICE_ACCESS_PS = 260

L = []


def p(s=""):
    L.append(s)


def banner(title):
    p("// " + "=" * 75)
    p(f"// {title}")
    p("// " + "=" * 75)


p("// ---------------------------------------------------------------------------")
p("// AUTO-GENERATED by gen/vc3d_gen_macro_slice_array.py -- DO NOT HAND EDIT.")
p("//")
p(f"// Macro-sliced cache-die array: {BANKS} banks x {SUBARRAYS} subarrays x {SLICES} slices")
p(f"// each {SLICE_DEPTH} x {DW} b, divided local bitlines, ~{SLICE_ACCESS_PS} ps access")
p(f"// Payload capacity: {BANKS*SUBARRAYS*ROWS*128//8//1024//1024} MiB data + SECDED check bits")
p("//")
p("// Bank = unit of independent access, power gating, and thermal reporting.")
p("// Subarray = unit produced by the SRAM compiler and repaired by BISR.")
p("// Slice = one 256 x 148 direct SRAM macro with divided local bitline.")
p("// ---------------------------------------------------------------------------")
p("`timescale 1ns/1ps")
p('`include "vc3d_params.vh"')
p('`include "vc3d_defines.vh"')
p("")

# ---------------------------------------------------------------- bank modules
for b in range(BANKS):
    banner(f"Macro-sliced Bank {b:02d}")
    p(f"module vc3d_stack_macro_bank_{b:02d} (")
    p("    input  wire                     clk,")
    p("    input  wire                     rst,")
    p("    input  wire                     ce,")
    p("    input  wire                     we,")
    p(f"    input  wire [{SUBARRAYS.bit_length()-2}:0]                sub_sel,")
    p(f"    input  wire [{AW-1}:0]               row_addr,")
    p(f"    input  wire [{DW-1}:0]              wdata,")
    p(f"    input  wire [{DW-1}:0]              wbit_mask,")
    p(f"    output wire [{DW-1}:0]              rdata,")
    p("    output wire                     rvalid,")
    p(f"    input  wire [{SUBARRAYS*SPARE_ROWS-1}:0]              rpr_row_valid,")
    p(f"    input  wire [{SUBARRAYS*SPARE_ROWS*AW-1}:0]             rpr_row_addr,")
    p(f"    input  wire [{SUBARRAYS*SPARE_COLS-1}:0]              rpr_col_valid,")
    p(f"    input  wire [{SUBARRAYS*SPARE_COLS*COL_ID_W-1}:0]             rpr_col_id,")
    p("    input  wire                     sleep,")
    p("    input  wire                     deep_sleep,")
    p("    input  wire                     retention,")
    p("    input  wire [3:0]               wa_code,")
    p("    input  wire [3:0]               ra_code,")
    p(f"    output wire [{SUBARRAYS-1}:0]              sub_spare_row_hit,")
    p(f"    output wire [{SUBARRAYS-1}:0]              sub_access_blocked,")
    p("    output wire                     bank_busy")
    p(");")
    p("")
    p(f"    wire [{SUBARRAYS-1}:0] sub_ce;")
    p(f"    wire [{SUBARRAYS-1}:0] sub_rvalid;")
    for s in range(SUBARRAYS):
        p(f"    wire [{DW-1}:0] sub_rdata_{s:02d};")
    p("")
    p("    // one-hot subarray decode")
    for s in range(SUBARRAYS):
        p(f"    assign sub_ce[{s:2d}] = ce & (sub_sel == {SUBARRAYS.bit_length()-1}'d{s});")
    p("")
    for s in range(SUBARRAYS):
        p(f"    // ---- bank {b:02d} subarray {s:02d} "
          f"({ROWS} x {DW}, {SLICES} direct macro slices x {SLICE_DEPTH} rows) ----")
        p(f"    vc3d_stack_macro_subarray #(")
        p(f"        .DEPTH       ({ROWS}),")
        p(f"        .AW          ({AW}),")
        p(f"        .DW          ({DW}),")
        p(f"        .SPARE_ROWS  ({SPARE_ROWS}),")
        p(f"        .SPARE_COLS  ({SPARE_COLS}),")
        p(f"        .COL_GROUP_W ({DW // SPARE_COLS}),")
        p(f"        .COL_ID_W    ({COL_ID_W}),")
        p(f"        .MACRO_SLICES ({SLICES}),")
        p(f"        .SLICE_DEPTH ({SLICE_DEPTH}),")
        p(f"        .SLICE_AW    ({SLICE_AW}),")
        p(f"        .SLICE_ACCESS({SLICE_ACCESS_PS})")
        p(f"    ) u_sub_{s:02d} (")
        p("        .clk               (clk),")
        p("        .rst               (rst),")
        p(f"        .ce                (sub_ce[{s}]),")
        p("        .we                (we),")
        p("        .addr              (row_addr),")
        p("        .wdata             (wdata),")
        p("        .wbit_mask         (wbit_mask),")
        p(f"        .rdata             (sub_rdata_{s:02d}),")
        p(f"        .rvalid            (sub_rvalid[{s}]),")
        p(f"        .rpr_row_valid     (rpr_row_valid[{s*SPARE_ROWS} +: {SPARE_ROWS}]),")
        p(f"        .rpr_row_addr      (rpr_row_addr[{s*SPARE_ROWS*AW} +: {SPARE_ROWS*AW}]),")
        p(f"        .rpr_col_valid     (rpr_col_valid[{s*SPARE_COLS} +: {SPARE_COLS}]),")
        p(f"        .rpr_col_id        (rpr_col_id[{s*SPARE_COLS*COL_ID_W} +: {SPARE_COLS*COL_ID_W}]),")
        p("        .sleep             (sleep),")
        p("        .deep_sleep        (deep_sleep),")
        p("        .retention         (retention),")
        p("        .wa_code           (wa_code),")
        p("        .ra_code           (ra_code),")
        p(f"        .spare_row_hit     (sub_spare_row_hit[{s}]),")
        p("        .spare_row_hit_vec (),")
        p(f"        .access_blocked    (sub_access_blocked[{s}])")
        p("    );")
        p("")
    p(f"    reg [{SUBARRAYS.bit_length()-2}:0] sub_sel_q, sub_sel_q2;")
    p("    always @(posedge clk or posedge rst) begin")
    p("        if (rst) begin sub_sel_q <= 4'd0; sub_sel_q2 <= 4'd0; end")
    p("        else     begin sub_sel_q <= sub_sel; sub_sel_q2 <= sub_sel_q; end")
    p("    end")
    p("")
    p(f"    reg [{DW-1}:0] rdata_mux;")
    p("    always @* begin")
    p("        case (sub_sel_q2)")
    for s in range(SUBARRAYS):
        p(f"            {s:2d}'d{s:2d}: rdata_mux = sub_rdata_{s:02d};")
    p("            default: rdata_mux = 144'd0;")
    p("        endcase")
    p("    end")
    p("")
    p("    assign rdata  = rdata_mux;")
    p("    assign rvalid = |sub_rvalid;")
    p("    assign bank_busy = ce;")
    p("")
    p("endmodule")
    p("")

# ---------------------------------------------------------------- die array top
banner("Macro-sliced die array")
p("module vc3d_stack_macro_die_array (")
p("    input  wire                     clk,")
p("    input  wire                     rst,")
p("    input  wire                     ce,")
p("    input  wire                     we,")
p("    input  wire [4:0]               bank_sel,")
p("    input  wire [3:0]               sub_sel,")
p("    input  wire [9:0]               row_addr,")
p("    input  wire [143:0]             wdata,")
p("    input  wire [143:0]             wbit_mask,")
p("    output wire [143:0]             rdata,")
p("    output wire                     rvalid,")
p(f"    input  wire [{BANKS*SUBARRAYS*SPARE_ROWS-1}:0]             rpr_row_valid,")
p(f"    input  wire [{BANKS*SUBARRAYS*SPARE_ROWS*AW-1}:0]          rpr_row_addr,")
p(f"    input  wire [{BANKS*SUBARRAYS*SPARE_COLS-1}:0]             rpr_col_valid,")
p(f"    input  wire [{BANKS*SUBARRAYS*SPARE_COLS*COL_ID_W-1}:0]    rpr_col_id,")
p(f"    input  wire [{BANKS-1}:0]            bank_sleep,")
p(f"    input  wire [{BANKS-1}:0]            bank_deep_sleep,")
p(f"    input  wire [{BANKS-1}:0]            bank_retention,")
p("    input  wire [3:0]               wa_code,")
p("    input  wire [3:0]               ra_code,")
p(f"    output wire [{BANKS-1}:0]            bank_busy,")
p(f"    output wire [{BANKS*SUBARRAYS-1}:0]      spare_row_hit,")
p(f"    output wire [{BANKS*SUBARRAYS-1}:0]      access_blocked")
p(");")
p("")
p("    wire [31:0] bank_ce;")
p("    wire [31:0] bank_rvalid;")
for b in range(BANKS):
    p(f"    wire [143:0] bank_rdata_{b:02d};")
p("")
for b in range(BANKS):
    p(f"    assign bank_ce[{b:2d}] = ce & (bank_sel == 5'd{b});")
p("")
for b in range(BANKS):
    p(f"    vc3d_stack_macro_bank_{b:02d} u_bank_{b:02d} (")
    p("        .clk                (clk),")
    p("        .rst                (rst),")
    p(f"        .ce                 (bank_ce[{b}]),")
    p("        .we                 (we),")
    p("        .sub_sel            (sub_sel),")
    p("        .row_addr           (row_addr),")
    p("        .wdata              (wdata),")
    p("        .wbit_mask          (wbit_mask),")
    p(f"        .rdata              (bank_rdata_{b:02d}),")
    p(f"        .rvalid             (bank_rvalid[{b}]),")
    p(f"        .rpr_row_valid      (rpr_row_valid[{b*SUBARRAYS*SPARE_ROWS} +: {SUBARRAYS*SPARE_ROWS}]),")
    p(f"        .rpr_row_addr       (rpr_row_addr[{b*SUBARRAYS*SPARE_ROWS*AW} +: {SUBARRAYS*SPARE_ROWS*AW}]),")
    p(f"        .rpr_col_valid      (rpr_col_valid[{b*SUBARRAYS*SPARE_COLS} +: {SUBARRAYS*SPARE_COLS}]),")
    p(f"        .rpr_col_id         (rpr_col_id[{b*SUBARRAYS*SPARE_COLS*COL_ID_W} +: {SUBARRAYS*SPARE_COLS*COL_ID_W}]),")
    p(f"        .sleep              (bank_sleep[{b}]),")
    p(f"        .deep_sleep         (bank_deep_sleep[{b}]),")
    p(f"        .retention          (bank_retention[{b}]),")
    p("        .wa_code            (wa_code),")
    p("        .ra_code            (ra_code),")
    p(f"        .sub_spare_row_hit  (spare_row_hit[{b*SUBARRAYS} +: {SUBARRAYS}]),")
    p(f"        .sub_access_blocked (access_blocked[{b*SUBARRAYS} +: {SUBARRAYS}]),")
    p(f"        .bank_busy          (bank_busy[{b}])")
    p("    );")
    p("")
p("")
p("    reg [4:0] bank_sel_q, bank_sel_q2;")
p("    always @(posedge clk or posedge rst) begin")
p("        if (rst) begin bank_sel_q <= 5'd0; bank_sel_q2 <= 5'd0; end")
p("        else     begin bank_sel_q <= bank_sel; bank_sel_q2 <= bank_sel_q; end")
p("    end")
p("")
p("    reg [143:0] rdata_mux;")
p("    always @* begin")
p("        case (bank_sel_q)")
for b in range(BANKS):
    p(f"            5'd{b:2d}: rdata_mux = bank_rdata_{b:02d};")
p("            default: rdata_mux = 144'd0;")
p("        endcase")
p("    end")
p("")
p("    assign rdata  = rdata_mux;")
p("    assign rvalid = |bank_rvalid;")
p("")
p("endmodule")
p("")

OUT.write_text("\n".join(L) + "\n")
print(f"wrote {OUT} ({len(L)} lines)")
