#!/usr/bin/env python3
"""Generate the fully expanded stacked-die SRAM array for VCACHE-3D.

The cache dielet is 24 MiB of hybrid-bonded high-density SRAM per slice,
organised as:

    32 banks  x  16 subarrays  x  1024 rows  x  148 bits
    = 32 * 16 * 1024 * 144 payload bits = 75,497,472 bits = 9 MiB of payload
      per "plane"; the array below is instantiated as PLANES planes (default 2)
      and two 128-bit sublines are packed per row, giving 24 MiB usable with
      16 bits of SECDED check per 128 bits of data.

Every bank is emitted as its own module with all 16 subarray instances written
out explicitly (rather than a generate loop) because:

  * physical design places and power-gates each bank individually, and the
    floorplan scripts in pd/openroad key off the instance names produced here;
  * the redundancy fabric assigns spare rows/columns per subarray, so the
    per-instance repair wiring is not uniform after fusing;
  * flat RTL keeps synthesis/PnR/STA/formal all looking at the same netlist.

Run `make -C _noc/vcache3d gen` to regenerate; `make check-generated` diffs the
checked-in artifacts against a fresh run.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "rtl" / "stack" / "vc3d_stack_bank_array.v"

BANKS = 32
SUBARRAYS = 16
ROWS = 1024
AW = 10
DW = 144
SPARE_ROWS = 4
SPARE_COLS = 4
COL_ID_W = 6

L = []


def p(s=""):
    L.append(s)


def banner(title):
    p("// " + "=" * 75)
    p(f"// {title}")
    p("// " + "=" * 75)


p("// ---------------------------------------------------------------------------")
p("// AUTO-GENERATED by gen/vc3d_gen_stack_array.py -- DO NOT HAND EDIT.")
p("//")
p(f"// Stacked cache-die array: {BANKS} banks x {SUBARRAYS} subarrays x {ROWS} rows x {DW} b")
p(f"// Payload capacity: {BANKS*SUBARRAYS*ROWS*128//8//1024//1024} MiB data + SECDED check bits")
p("//")
p("// Bank = unit of independent access, power gating, and thermal reporting.")
p("// Subarray = unit produced by the SRAM compiler and repaired by BISR.")
p("// ---------------------------------------------------------------------------")
p("`timescale 1ns/1ps")
p('`include "vc3d_params.vh"')
p('`include "vc3d_defines.vh"')
p("")

# ---------------------------------------------------------------- bank modules
for b in range(BANKS):
    banner(f"Bank {b:02d}")
    p(f"module vc3d_stack_bank_{b:02d} (")
    p("    input  wire                     clk,")
    p("    input  wire                     rst,")
    p("    input  wire                     ce,")
    p("    input  wire                     we,")
    p(f"    input  wire [{SUBARRAYS.bit_length()-2}:0]                sub_sel,")
    p(f"    input  wire [{AW-1}:0]               row_addr,")
    p(f"    input  wire [{DW-1}:0]              wdata,")
    p(f"    input  wire [{DW-1}:0]              wbit_mask,")
    p(f"    output wire [{DW-1}:0]              rdata,")
    p("    output wire                     rvalid,")
    p(f"    input  wire [{SUBARRAYS*SPARE_ROWS-1}:0]              rpr_row_valid,")
    p(f"    input  wire [{SUBARRAYS*SPARE_ROWS*AW-1}:0]             rpr_row_addr,")
    p(f"    input  wire [{SUBARRAYS*SPARE_COLS-1}:0]              rpr_col_valid,")
    p(f"    input  wire [{SUBARRAYS*SPARE_COLS*COL_ID_W-1}:0]             rpr_col_id,")
    p("    input  wire                     sleep,")
    p("    input  wire                     deep_sleep,")
    p("    input  wire                     retention,")
    p("    input  wire [3:0]               wa_code,")
    p("    input  wire [3:0]               ra_code,")
    p(f"    output wire [{SUBARRAYS-1}:0]              sub_spare_row_hit,")
    p(f"    output wire [{SUBARRAYS-1}:0]              sub_access_blocked,")
    p("    output wire                     bank_busy")
    p(");")
    p("")
    p(f"    wire [{SUBARRAYS-1}:0] sub_ce;")
    p(f"    wire [{SUBARRAYS-1}:0] sub_rvalid;")
    for s in range(SUBARRAYS):
        p(f"    wire [{DW-1}:0] sub_rdata_{s:02d};")
    p("")
    p("    // one-hot subarray decode")
    for s in range(SUBARRAYS):
        p(f"    assign sub_ce[{s:2d}] = ce & (sub_sel == {SUBARRAYS.bit_length()-1}'d{s});")
    p("")
    for s in range(SUBARRAYS):
        p(f"    // ---- bank {b:02d} subarray {s:02d} "
          f"({ROWS} x {DW}, {SPARE_ROWS} spare rows, {SPARE_COLS} spare cols) ----")
        p(f"    vc3d_stack_subarray #(")
        p(f"        .DEPTH       ({ROWS}),")
        p(f"        .AW          ({AW}),")
        p(f"        .DW          ({DW}),")
        p(f"        .SPARE_ROWS  ({SPARE_ROWS}),")
        p(f"        .SPARE_COLS  ({SPARE_COLS}),")
        p(f"        .COL_GROUP_W ({DW//SPARE_COLS}),")
        p(f"        .COL_ID_W    ({COL_ID_W})")
        p(f"    ) u_sub_{s:02d} (")
        p( "        .clk               (clk),")
        p( "        .rst               (rst),")
        p(f"        .ce                (sub_ce[{s}]),")
        p( "        .we                (we),")
        p( "        .addr              (row_addr),")
        p( "        .wdata             (wdata),")
        p( "        .wbit_mask         (wbit_mask),")
        p(f"        .rdata             (sub_rdata_{s:02d}),")
        p(f"        .rvalid            (sub_rvalid[{s}]),")
        p(f"        .rpr_row_valid     (rpr_row_valid[{s*SPARE_ROWS} +: {SPARE_ROWS}]),")
        p(f"        .rpr_row_addr      (rpr_row_addr[{s*SPARE_ROWS*AW} +: {SPARE_ROWS*AW}]),")
        p(f"        .rpr_col_valid     (rpr_col_valid[{s*SPARE_COLS} +: {SPARE_COLS}]),")
        p(f"        .rpr_col_id        (rpr_col_id[{s*SPARE_COLS*COL_ID_W} +: {SPARE_COLS*COL_ID_W}]),")
        p( "        .sleep             (sleep),")
        p( "        .deep_sleep        (deep_sleep),")
        p( "        .retention         (retention),")
        p( "        .wa_code           (wa_code),")
        p( "        .ra_code           (ra_code),")
        p(f"        .spare_row_hit     (sub_spare_row_hit[{s}]),")
        p( "        .spare_row_hit_vec (),")
        p(f"        .access_blocked    (sub_access_blocked[{s}])")
        p("    );")
        p("")
    # registered select for the read mux (subarray latency is 1 cycle)
    p(f"    reg [{SUBARRAYS.bit_length()-2}:0] sub_sel_q;")
    p("    always @(posedge clk or posedge rst) begin")
    p(f"        if (rst) sub_sel_q <= {SUBARRAYS.bit_length()-1}'d0;")
    p("        else     sub_sel_q <= sub_sel;")
    p("    end")
    p("")
    p(f"    reg [{DW-1}:0] rdata_mux;")
    p("    always @* begin")
    p("        case (sub_sel_q)")
    for s in range(SUBARRAYS):
        p(f"            {SUBARRAYS.bit_length()-1}'d{s:2d}: rdata_mux = sub_rdata_{s:02d};")
    p(f"            default: rdata_mux = {DW}'d0;")
    p("        endcase")
    p("    end")
    p("")
    # Bank output pipeline register.  The 16:1 subarray mux plus the 32:1
    # bank mux plus the wire back to the bond pads does not fit in one array
    # cycle after a 465 ps subarray access; registering at the bank boundary
    # splits it into two comfortable halves (pd/scripts/timing_model.py).
    p(f"    reg [{DW-1}:0] rdata_q;")
    p("    reg          rvalid_q;")
    p("    always @(posedge clk or posedge rst) begin")
    p(f"        if (rst) begin rdata_q <= {DW}'d0; rvalid_q <= 1'b0; end")
    p("        else     begin rdata_q <= rdata_mux; rvalid_q <= |sub_rvalid; end")
    p("    end")
    p("")
    p("    assign rdata     = rdata_q;")
    p("    assign rvalid    = rvalid_q;")
    p("    assign bank_busy = |sub_ce;")
    p("")
    p("endmodule")
    p("")

# ------------------------------------------------------------------- die array
banner("Stacked cache-die array top: all banks, expanded")
p("module vc3d_stack_die_array (")
p("    input  wire                     clk,")
p("    input  wire                     rst,")
p("    input  wire                     ce,")
p("    input  wire                     we,")
p(f"    input  wire [{BANKS.bit_length()-2}:0]               bank_sel,")
p(f"    input  wire [{SUBARRAYS.bit_length()-2}:0]               sub_sel,")
p(f"    input  wire [{AW-1}:0]              row_addr,")
p(f"    input  wire [{DW-1}:0]             wdata,")
p(f"    input  wire [{DW-1}:0]             wbit_mask,")
p(f"    output wire [{DW-1}:0]             rdata,")
p("    output wire                     rvalid,")
p(f"    input  wire [{BANKS*SUBARRAYS*SPARE_ROWS-1}:0]            rpr_row_valid,")
p(f"    input  wire [{BANKS*SUBARRAYS*SPARE_ROWS*AW-1}:0]           rpr_row_addr,")
p(f"    input  wire [{BANKS*SUBARRAYS*SPARE_COLS-1}:0]            rpr_col_valid,")
p(f"    input  wire [{BANKS*SUBARRAYS*SPARE_COLS*COL_ID_W-1}:0]           rpr_col_id,")
p(f"    input  wire [{BANKS-1}:0]              bank_sleep,")
p(f"    input  wire [{BANKS-1}:0]              bank_deep_sleep,")
p(f"    input  wire [{BANKS-1}:0]              bank_retention,")
p("    input  wire [3:0]               wa_code,")
p("    input  wire [3:0]               ra_code,")
p(f"    output wire [{BANKS-1}:0]              bank_busy,")
p(f"    output wire [{BANKS*SUBARRAYS-1}:0]            spare_row_hit,")
p(f"    output wire [{BANKS*SUBARRAYS-1}:0]            access_blocked")
p(");")
p("")
p(f"    wire [{BANKS-1}:0] bank_ce;")
p(f"    wire [{BANKS-1}:0] bank_rvalid;")
for b in range(BANKS):
    p(f"    wire [{DW-1}:0] bank_rdata_{b:02d};")
p("")
for b in range(BANKS):
    p(f"    assign bank_ce[{b:2d}] = ce & (bank_sel == {BANKS.bit_length()-1}'d{b});")
p("")
RS = SUBARRAYS * SPARE_ROWS
RA = SUBARRAYS * SPARE_ROWS * AW
CS = SUBARRAYS * SPARE_COLS
CI = SUBARRAYS * SPARE_COLS * COL_ID_W
for b in range(BANKS):
    p(f"    vc3d_stack_bank_{b:02d} u_bank_{b:02d} (")
    p( "        .clk                (clk),")
    p( "        .rst                (rst),")
    p(f"        .ce                 (bank_ce[{b}]),")
    p( "        .we                 (we),")
    p( "        .sub_sel            (sub_sel),")
    p( "        .row_addr           (row_addr),")
    p( "        .wdata              (wdata),")
    p( "        .wbit_mask          (wbit_mask),")
    p(f"        .rdata              (bank_rdata_{b:02d}),")
    p(f"        .rvalid             (bank_rvalid[{b}]),")
    p(f"        .rpr_row_valid      (rpr_row_valid[{b*RS} +: {RS}]),")
    p(f"        .rpr_row_addr       (rpr_row_addr[{b*RA} +: {RA}]),")
    p(f"        .rpr_col_valid      (rpr_col_valid[{b*CS} +: {CS}]),")
    p(f"        .rpr_col_id         (rpr_col_id[{b*CI} +: {CI}]),")
    p(f"        .sleep              (bank_sleep[{b}]),")
    p(f"        .deep_sleep         (bank_deep_sleep[{b}]),")
    p(f"        .retention          (bank_retention[{b}]),")
    p( "        .wa_code            (wa_code),")
    p( "        .ra_code            (ra_code),")
    p(f"        .sub_spare_row_hit  (spare_row_hit[{b*SUBARRAYS} +: {SUBARRAYS}]),")
    p(f"        .sub_access_blocked (access_blocked[{b*SUBARRAYS} +: {SUBARRAYS}]),")
    p(f"        .bank_busy          (bank_busy[{b}])")
    p("    );")
    p("")
p(f"    reg [{BANKS.bit_length()-2}:0] bank_sel_q, bank_sel_q2;")
p("    always @(posedge clk or posedge rst) begin")
p(f"        if (rst) begin bank_sel_q <= {BANKS.bit_length()-1}'d0; bank_sel_q2 <= {BANKS.bit_length()-1}'d0; end")
p("        else     begin bank_sel_q <= bank_sel; bank_sel_q2 <= bank_sel_q; end")
p("    end")
p("")
p(f"    reg [{DW-1}:0] rdata_mux;")
p("    always @* begin")
p("        case (bank_sel_q)")
for b in range(BANKS):
    p(f"            {BANKS.bit_length()-1}'d{b:2d}: rdata_mux = bank_rdata_{b:02d};")
p(f"            default: rdata_mux = {DW}'d0;")
p("        endcase")
p("    end")
p("")
p("    assign rdata  = rdata_mux;")
p("    assign rvalid = |bank_rvalid;")
p("")
p("endmodule")
p("")

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(L) + "\n")
print(f"wrote {OUT} ({len(L)+1} lines)")
